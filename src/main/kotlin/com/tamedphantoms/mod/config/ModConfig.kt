package com.tamedphantoms.mod.config

/**
 * Внутренние технические константы мода — то, что скорее "чувство/ощущение
 * от игры", чем правило геймплея, и поэтому не вынесено в игровой конфиг
 * (экран настроек не должен быть захламлён десятком параметров анимации).
 *
 * Игровые правила, которые ИМЕЕТ смысл настраивать за сервер/при запуске
 * (предмет приручения, шанс приручения, радиус отпугивания, длительность
 * самозащиты) — теперь в [ServerConfig], полноценном конфиге NeoForge
 * с сохранением на диск, синхронизацией в мультиплеере и экраном в игре.
 */
object ModConfig {

    /**
     * Крейсерская горизонтальная скорость управляемого полёта при множителе ×2,
     * в блоках/тик. Это прежнее поведение питомца. Игровой множитель
     * ([com.tamedphantoms.mod.config.ServerConfig.flightSpeed], по умолчанию 1.25)
     * умножает это число на `множитель / 2`: 2.0 оставляет как есть, 1.25 берёт 0.625.
     * Набор высоты, пике и петли меряются от этой скорости в [com.tamedphantoms.mod.util.PhantomFlightModel].
     */
    const val FLIGHT_SPEED_BLOCKS_PER_TICK: Double = 0.84

    // Отдельный кулдаун для "фоновых" звуков (Phantom idle*.ogg) не нужен:
    // ванильный Phantom.getAmbientSound() уже возвращает SoundEvents.PHANTOM_AMBIENT
    // (который сам по себе случайно выбирает один из idle-вариантов при проигрывании),
    // а периодичность проигрывания управляется унаследованным Mob.getAmbientSoundInterval() —
    // мы его не трогаем, значит поведение "иногда, не слишком часто" достаётся бесплатно.

    /** Радиус (в блоках), на котором прирученный фантом поворачивает голову к игроку. */
    const val LOOK_AT_PLAYER_RANGE: Double = 6.0
}
